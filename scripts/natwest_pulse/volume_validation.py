"""NatWest volume validation (HL-18): our illustrative figures against the public anchors.

Writes qa/natwest_volume_validation.md (metric | ours | anchor | ratio | verdict). Anything more than 2x off an anchor
fails unless it is justified here. Metrics with no anchor are listed as assumptions, never as validated.
Exit code 1 when an anchored metric is more than 2x off without a justification.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCALE = ROOT / "data" / "seed" / "natwest_pulse" / "natwest_scale.json"
OUT_MD = ROOT / "qa" / "natwest_volume_validation.md"
JUSTIFIED: dict[str, str] = {}


def main() -> int:
    s = json.loads(SCALE.read_text(encoding="utf-8"))
    a, o, asm = s["anchors"], s["ours"], s["assumptions"]
    rows = [
        ("Complaints per half-year (group)", o["complaints_per_half_year"], a["h1_complaints"]),
        ("Complaints per 1,000 accounts, half-year", o["per_1000_accounts_half_year"], a["per_1000_accounts"]),
        ("Share upheld", o["upheld"], a["upheld"]),
        ("Share closed within 3 days", o["closed_3d"], a["closed_3d"]),
    ]
    out = [
        "# NatWest · volume validation (HL-18)",
        "",
        "Generated by `scripts/natwest_pulse/volume_validation.py` from `data/seed/natwest_pulse/natwest_scale.json`. Anchors are",
        "the figures the brief quotes from the research pack (not supplied; NW-D01). Ratio = ours / anchor.",
        "",
        "| Metric | Ours | Anchor | Ratio | Verdict |",
        "|---|---|---|---|---|",
    ]
    bad = 0
    for name, ours, anchor in rows:
        ratio = ours / anchor if anchor else None
        ok = ratio is not None and 0.5 <= ratio <= 2
        verdict = "PASS" if ok else ("JUSTIFIED: " + JUSTIFIED[name] if name in JUSTIFIED else "FAIL")
        bad += verdict == "FAIL"
        out.append(f"| {name} | {ours:,} | {anchor:,} | {ratio:.2f} | {verdict} |")
    out += [
        "",
        "## Assumptions (no anchor until discovery)",
        "",
        "| Metric | Ours | Basis |",
        "|---|---|---|",
        f"| Contacts per week, calls + Cora + branch | {o['contacts_week']:,} | {asm['contacts_per_customer_year']} contacts per customer per year × {asm['customers']:,} customers |",
        f"| Negative share of internal contacts | {o['negative_share']:.1%} | HL-19 target about 12% (9–16% by product) |",
        f"| Brand split of customers | {asm['brand_share']} | Assumption |",
        f"| Segment split of customers | {asm['segment_share']} | Assumption |",
        f"| Product shape of complaints | {asm['product_complaint_shape']} | Assumption; the return's per-product shape is in the research pack |",
        f"| Push payment scam claims per week | {asm['app_claims_week']:,} | Assumption |",
        f"| Fraud alerts triaged per week | {asm['fraud_alerts_week']:,} | Assumption |",
        f"| Share of final responses drafted by AI | {asm['ai_letter_share']:.0%} | Assumption |",
        "",
        "Stock versus flow: the Ombudsman states are a stock as at the freeze; the window figures are flows.",
    ]
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"volume_validation (natwest): {len(rows)} anchored metrics, {bad} fail(s) -> {OUT_MD.relative_to(ROOT)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
